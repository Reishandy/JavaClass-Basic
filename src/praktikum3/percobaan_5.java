package praktikum3;

public class percobaan_5 {
    public static void main(String[] args) {
        int i = 1;

        System.out.println("i : " + i);
        System.out.println("++i : " + ++i); //Tambah dulu baru print
        System.out.println("i++ : " + i++); //Print dulu baru tambah
        System.out.println("i : " + i);
        System.out.println("--i : " + --i);
        System.out.println("i-- : " + i--);
        System.out.println("i : " + i);
    }
}
