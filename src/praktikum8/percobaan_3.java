package praktikum8;

public class percobaan_3 {
    public static void main(String[] args) {
        // Pembuatan array dengan isi
        // Berisi 10, 100, 25, 44, 71, 7, 0
        int arr[] = { 10, 100, 25, 44, 71, 7, 0 };

        // for loop iterable, setiap elemen dari array 'arr'
        // dimasukkan ke variabel i
        for (int i : arr) {

            // dan di print 'i' / elemen dari arr
            System.out.print(i);
        }
    }
}
